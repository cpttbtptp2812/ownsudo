CREATE TABLE agent_trace_span (
    id VARCHAR(64) NOT NULL,
    agent_id VARCHAR(64) NOT NULL,
    trace_id VARCHAR(64) NOT NULL,
    span_id VARCHAR(64) NOT NULL,
    parent_span_id VARCHAR(64) NULL,
    run_id VARCHAR(64) NULL,
    name VARCHAR(200) NOT NULL,
    span_kind VARCHAR(32) NOT NULL DEFAULT 'INTERNAL',
    status VARCHAR(24) NOT NULL DEFAULT 'UNSET',
    started_at DATETIME(6) NOT NULL,
    ended_at DATETIME(6) NULL,
    duration_ms BIGINT NULL,
    input_tokens BIGINT NULL,
    output_tokens BIGINT NULL,
    total_tokens BIGINT NULL,
    usage_source VARCHAR(24) NOT NULL DEFAULT 'MISSING',
    attributes_json LONGTEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_trace_span_agent_span (agent_id, trace_id, span_id),
    INDEX idx_trace_span_agent_trace_time (agent_id, trace_id, started_at),
    INDEX idx_trace_span_agent_run (agent_id, run_id),
    CONSTRAINT fk_trace_span_agent FOREIGN KEY (agent_id) REFERENCES agent_definition(id)
);
